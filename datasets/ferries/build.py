"""Skerry Line, a fictional island ferry operator: generated data (generate.py, seeded, no
downloads) written to ferries.duckdb, plus two variants that keep a deterministic sample of
sailings together with their bookings, booked vehicles and refunds."""

from __future__ import annotations

import sys
from pathlib import Path

import duckdb

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
from common import build_variants, write_manifest  # noqa: E402  # pylint: disable=wrong-import-position
from generate import write_tables  # noqa: E402  # pylint: disable=wrong-import-position

MAIN = HERE / "ferries.duckdb"

# A variant keeps or drops a whole sailing: its bookings, and through them its booked vehicles
# and refunds, are sampled by the same sailing_id.
_SAILING_OF = "(SELECT b.sailing_id FROM src.bookings b WHERE b.booking_ref = {table}.booking_ref)"
FACT_KEYS = {
    "sailings": "sailing_id",
    "bookings": "sailing_id",
    "booked_vehicles": _SAILING_OF.format(table="booked_vehicles"),
    "refunds": _SAILING_OF.format(table="refunds"),
}


def main() -> None:
    MAIN.unlink(missing_ok=True)
    con = duckdb.connect(str(MAIN))
    write_tables(con)
    con.execute("CHECKPOINT")
    con.close()
    variants = build_variants(MAIN, FACT_KEYS)
    write_manifest(
        HERE,
        {
            "name": "ferries",
            "source": "Generated by datasets/ferries/generate.py (numpy default_rng, fixed seeds): Skerry Line, a fictional island ferry operator, 2022-2025",
            "license": "CC0 1.0. Fictional: any resemblance to real operators, people or places is coincidental",
        },
        {"main": MAIN, **variants},
    )


if __name__ == "__main__":
    main()
